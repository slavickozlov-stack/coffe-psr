    def get_templates(self, specialty_id: Optional[str] = None) -> List[Dict]:
        with open(TEMPLATES_FILE, "r", encoding="utf-8") as f:
            templates = json.load(f)
        if specialty_id:
            return [t for t in templates if t.get("specialty_id") == specialty_id]
        return templates

    def get_norm_docs(self, category: Optional[str] = None) -> List[Dict]:
        """
        Возвращает нормативные документы.
        Если указана специальность (например, 'Электрик'), возвращаются:
        1. Документы, относящиеся к этой специальности.
        2. Общие документы ('Общий'), которые должны быть доступны у всех!
        """
        with open(NORM_DOCS_FILE, "r", encoding="utf-8") as f:
            docs = json.load(f)

        if not category or category == "Все":
            return docs

        result = []
        for d in docs:
            cats = d.get("categories", [d.get("category", "")])
            # Если документ относится к выбранной специальности или является общим для всех
            if category in cats or "Общий" in cats or "all" in cats:
                result.append(d)
        return result

